"""Real Edge browser end-to-end checks against the disposable QA database."""
import json
import os
import re
from pathlib import Path
import time
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1]
os.environ['TEMP']=os.environ['TMP']=str(ROOT/'.runtime/tmp')
PASSWORD=json.loads((ROOT/'.runtime/qa-credentials.json').read_text())['password']
OUTPUT=ROOT/'test-results/browser'
OUTPUT.mkdir(parents=True,exist_ok=True)

def run():
    checks=[];errors=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(channel='msedge',headless=True)
        context=browser.new_context(viewport={'width':1440,'height':1000},locale='zh-CN')
        page=context.new_page();page.set_default_timeout(15000)
        page.on('pageerror',lambda exc:errors.append(str(exc)))
        def screenshot(name):page.screenshot(path=str(OUTPUT/f'{name}.png'),full_page=True)
        def login(username):
            page.goto('http://127.0.0.1:8100/login')
            page.get_by_label('账号',exact=True).fill(username)
            page.get_by_label('密码',exact=True).fill(PASSWORD)
            page.get_by_role('button',name='登录',exact=True).click()
            expect(page.get_by_role('button',name='退出',exact=True)).to_be_visible()
        def logout():page.get_by_role('button',name='退出',exact=True).click();expect(page.get_by_role('button',name='登录',exact=True)).to_be_visible()
        def course(name,button):
            page.get_by_label('搜索课程',exact=True).fill(name)
            card=page.locator('article.course-card').filter(has=page.get_by_role('heading',name=name,exact=True))
            card.get_by_role('button',name=button,exact=True).click()
        login('student01')
        expect(page.get_by_role('heading',name='林晓，开始你的学习计划')).to_be_visible()
        expect(page.get_by_role('heading',name='程序设计基础',exact=True)).to_be_visible()
        screenshot('01-student-initial')
        for name in ['程序设计基础','离散数学','计算机导论','大学英语']:course(name,'加入首选')
        for name in ['线性代数','软件工程导论']:course(name,'加入备选')
        page.get_by_role('button',name='保存草稿',exact=True).click()
        expect(page.get_by_text('草稿已保存，正式选课和名额未改变',exact=True)).to_be_visible()
        page.reload();expect(page.get_by_text('已保存草稿',exact=True)).to_be_visible()
        page.get_by_role('button',name='提交选课',exact=True).dblclick()
        expect(page.get_by_text('选课提交成功，正式课表已更新',exact=True)).to_be_visible()
        page.get_by_role('tab',name='我的课表').click()
        expect(page.locator('.class-block')).to_have_count(4)
        screenshot('02-student-timetable')
        page.get_by_role('button',name='删除课表',exact=True).click()
        page.get_by_role('button',name='取消',exact=True).click()
        expect(page.locator('.class-block')).to_have_count(4)
        page.get_by_role('tab',name='学期成绩单').click()
        expect(page.get_by_role('cell',name='程序设计基础',exact=True)).to_be_visible()
        screenshot('03-student-grades')
        page.get_by_role('tab',name='课程选择').click()
        course('程序设计基础','已选首选 · 移除')
        course('计算机网络','加入首选')
        page.get_by_role('button',name='提交选课',exact=True).click()
        expect(page.locator('.el-alert').filter(has_text=re.compile('上课时间(冲突|重叠)'))).to_be_visible()
        page.reload()
        expect(page.locator('aside .selected-row')).to_have_count(6)
        page.get_by_label('搜索课程',exact=True).fill('程序设计基础')
        expect(page.get_by_role('button',name='已选首选 · 移除',exact=True)).to_be_visible()
        checks.append('学生：选课、草稿刷新、重复点击、冲突失败保留原课表、删除取消、成绩单')
        page.route('**/api/v1/auth/logout',lambda route:route.abort())
        page.get_by_role('button',name='退出',exact=True).click()
        expect(page.get_by_text(re.compile('退出登录未完成：.*连接'))).to_be_visible()
        expect(page.get_by_role('button',name='退出',exact=True)).to_be_visible()
        assert page.request.get('http://127.0.0.1:8100/api/v1/auth/me').status==200
        page.unroute('**/api/v1/auth/logout')
        checks.append('退出异常：网络失败保留登录状态并明确提示，恢复后可正常退出')
        logout();login('student03')
        course('操作系统','加入首选')
        course('数据结构','加入首选')
        page.get_by_role('button',name='保存草稿',exact=True).click()
        expect(page.get_by_text('草稿已保存，正式选课和名额未改变',exact=True)).to_be_visible()
        page.reload()
        expect(page.locator('aside .selected-row')).to_have_count(2)
        draft=page.request.get('http://127.0.0.1:8100/api/v1/student/schedules/2').json()
        assert draft['primary']==[] and sorted(draft['draft']['primary'])==[7,11]
        for name in ['程序设计基础','大学英语']:course(name,'加入首选')
        for name in ['离散数学','计算机导论']:course(name,'加入备选')
        page.get_by_role('button',name='提交选课',exact=True).click()
        expect(page.locator('.el-alert').filter(has_text='操作系统已满员')).to_contain_text('10/10')
        course('操作系统','已选首选 · 移除')
        course('线性代数','加入首选')
        page.get_by_role('button',name='提交选课',exact=True).click()
        expect(page.locator('.el-alert').filter(has_text='先修要求')).to_contain_text('程序设计基础')
        page.wait_for_timeout(5500)  # A successful seat poll must not erase a submission error.
        expect(page.locator('.el-alert').filter(has_text='先修要求')).to_be_visible()
        assert page.request.get('http://127.0.0.1:8100/api/v1/student/schedules/2').json()['primary']==[]
        checks.append('草稿与提交：满员/先修不足可保存并刷新，正式提交分别拒绝且不占名额')
        logout();login('professor01')
        page.get_by_label('搜索教学班',exact=True).fill('软件测试')
        page.locator('label.el-checkbox').filter(has=page.get_by_role('checkbox',name='选择任课 软件测试')).click()
        page.get_by_role('button',name='保存任课安排',exact=True).click()
        expect(page.get_by_text('任课安排已更新',exact=True)).to_be_visible()
        page.locator('label.el-checkbox').filter(has=page.get_by_role('checkbox',name='选择任课 软件测试')).click()
        page.get_by_role('button',name='保存任课安排',exact=True).click()
        expect(page.get_by_role('checkbox',name='选择任课 软件测试')).not_to_be_checked()
        page.get_by_label('搜索教学班',exact=True).fill('程序设计基础')
        page.get_by_role('button',name='查看名单',exact=True).click()
        expect(page.get_by_role('cell',name='林晓',exact=True)).to_be_visible()
        page.get_by_role('button',name='关闭',exact=True).click()
        page.get_by_role('combobox',name='选择学期').press('ArrowDown')
        page.get_by_role('option',name='上一学期 · 成绩归档').click()
        page.get_by_role('button',name='名单与成绩',exact=True).click()
        page.get_by_role('combobox',name='林晓的成绩').press('ArrowDown')
        page.get_by_role('option',name='B',exact=True).click()
        page.get_by_role('button',name='保存成绩',exact=True).click()
        expect(page.get_by_text('成绩已保存',exact=True)).to_be_visible()
        screenshot('04-professor-grades')
        page.get_by_role('button',name='关闭',exact=True).click()
        checks.append('教授：认领与取消任课、本人名单、历史成绩修改')
        logout();login('admin')
        page.get_by_role('link',name='学生信息').click()
        page.get_by_role('button',name='添加学生',exact=True).click()
        page.get_by_role('button',name='保存资料',exact=True).click()
        summary=page.get_by_role('alert',name='资料校验结果')
        expect(summary.locator('li')).to_have_count(4)
        for field in ['账号','姓名','出生日期','身份证号码']:expect(summary).to_contain_text(field)
        summary.get_by_role('button',name=re.compile('^账号：')).click()
        expect(page.get_by_label('新人员账号',exact=True)).to_be_focused()
        screenshot('09-person-required-fields')
        page.get_by_label('新人员账号',exact=True).fill('browser_student')
        page.get_by_label('姓名',exact=True).fill('浏览器验收学生')
        page.get_by_role('combobox',name='出生日期').fill('2004-01-01')
        page.get_by_role('combobox',name='出生日期').press('Tab')
        create_requests=[]
        page.on('request',lambda request:create_requests.append(request.url)
                if request.method=='POST' and request.url.endswith('/api/v1/registrar/people/student') else None)
        page.get_by_label('身份号码',exact=True).fill('123456789012345')
        page.get_by_role('button',name='保存资料',exact=True).click()
        expect(page.locator('[data-field=identity_number] .el-form-item__error')).to_contain_text('18位')
        expect(summary).to_contain_text('身份证号码')
        assert not create_requests,'Invalid identity should be rejected before submitting a request'
        identity_body='11010120040101601'  # Synthetic identity for disposable QA only.
        weights=(7,9,10,5,8,4,2,1,6,3,7,9,10,5,8,4,2)
        identity=identity_body+'10X98765432'[sum(int(d)*w for d,w in zip(identity_body,weights))%11]
        page.get_by_label('身份号码',exact=True).fill(identity)
        page.get_by_role('combobox',name='出生日期').fill('2003-01-01')
        page.get_by_role('combobox',name='出生日期').press('Tab')
        page.get_by_role('button',name='保存资料',exact=True).click()
        expect(page.locator('[data-field=identity_number] .el-form-item__error')).to_contain_text('不一致')
        assert not create_requests,'Inconsistent birthday should be rejected before submitting a request'
        page.get_by_role('combobox',name='出生日期').fill('2004-01-01')
        page.get_by_role('combobox',name='出生日期').press('Tab')
        page.get_by_label('新人员账号',exact=True).fill('student01')
        page.get_by_role('button',name='保存资料',exact=True).click()
        expect(page.locator('[data-field=username] .el-form-item__error')).to_contain_text('已')
        expect(summary).to_contain_text('账号')
        expect(page.get_by_label('姓名',exact=True)).to_have_value('浏览器验收学生')
        screenshot('10-person-duplicate-account')
        page.get_by_label('新人员账号',exact=True).fill('browser_student')
        expect(summary).not_to_be_visible()
        page.get_by_role('button',name='保存资料',exact=True).click()
        expect(page.get_by_role('dialog',name='请妥善交付初始密码')).to_be_visible()
        page.get_by_role('button',name='已记录',exact=True).click()
        page.get_by_label('搜索人员',exact=True).fill('browser_student')
        expect(page.get_by_role('cell',name='浏览器验收学生',exact=True)).to_be_visible()
        page.get_by_role('button',name='编辑',exact=True).click()
        page.get_by_label('姓名',exact=True).fill('浏览器验收已修改')
        page.get_by_role('button',name='保存资料',exact=True).click()
        expect(page.get_by_role('cell',name='浏览器验收已修改',exact=True)).to_be_visible()
        page.get_by_role('button',name='停用',exact=True).click()
        page.get_by_role('button',name='取消',exact=True).click()
        expect(page.get_by_role('cell',name='浏览器验收已修改',exact=True)).to_be_visible()
        screenshot('05-registrar-students')
        page.get_by_role('button',name='停用',exact=True).click()
        page.get_by_role('button',name='确认停用',exact=True).click()
        expect(page.get_by_role('cell',name='浏览器验收已修改',exact=True)).not_to_be_visible()
        page.locator('label.el-checkbox').filter(has_text='显示已停用人员').click()
        expect(page.get_by_role('cell',name='浏览器验收已修改',exact=True)).to_be_visible()
        checks.append('教务：一次列出4个必填错误、点击定位、短身份证/生日不符逐字段提示、服务端账号重复提示、修正后创建及修改停用')
        page.get_by_role('link',name='学期与选课').click()
        page.get_by_role('button',name='结束选课',exact=True).click()
        page.get_by_role('button',name='执行结束选课',exact=True).click()
        expect(page.get_by_role('dialog',name='结束选课处理结果')).to_be_visible()
        screenshot('06-registration-closed')
        page.get_by_role('button',name='完成',exact=True).click()
        page.get_by_role('link',name='计费任务').click()
        expect(page.get_by_role('heading',name='计费任务中心')).to_be_visible()
        expect(page.get_by_role('cell',name='已确认送达',exact=True).first).to_be_visible(timeout=30000)
        screenshot('07-billing-delivered')
        checks.append('结束选课：结果汇总、冻结学期、工作进程发送正式账单')
        logout();login('student01')
        expect(page.get_by_role('button',name='提交选课',exact=True)).to_be_disabled()
        page.get_by_role('tab',name='费用账单').click()
        expect(page.get_by_text('合计 ¥2400.00')).to_be_visible()
        screenshot('08-final-invoice')
        page.get_by_role('tab',name='学期成绩单').click()
        row=page.get_by_role('row').filter(has=page.get_by_role('cell',name='程序设计基础',exact=True))
        expect(row.get_by_text('B',exact=True)).to_be_visible()
        checks.append('学生重新登录：最终课表锁定、唯一账单、教授更新的成绩')
        browser.close()
    assert not errors,errors
    result={'passed':True,'browser':'Microsoft Edge (headless)','checks':checks,'javascript_errors':errors}
    (OUTPUT/'result.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False,indent=2))

